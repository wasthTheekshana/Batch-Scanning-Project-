"""Write docs/CENTRAL_API.md from the central service's own route and schema definitions.

    python scripts/gen_api_doc.py            # rewrite the document
    python scripts/gen_api_doc.py --check    # exit 1 when the document is out of date (the test uses this)

The document is generated, never edited by hand: a route added or changed in central/ shows up here
the next time this runs, and tests/central/test_api_doc.py fails until it has.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs" / "CENTRAL_API.md"

AUTH = {"require_admin": "admin session", "require_csrf": "CSRF header on changes",
        "require_pc": "PC API key (Bearer)"}
NO_AUTH = {"/admin/login": "nobody yet: this is the sign-in",
           "/pcs/register": "nobody yet: the one-time enrolment code in the body is the credential",
           "/healthz": "anyone (a liveness check; it reveals nothing)"}
HEADER = """# Central service API

*Generated by `scripts/gen_api_doc.py` from the service's own definitions. Do not edit by hand.*

The central service is a small FastAPI application (see `central/README.md` and
`central/deploy/DEPLOY.md`). Two kinds of caller use it:

- **Administrators** (the dashboard, or scripts) sign in with `POST /admin/login`. The reply sets a
  session cookie (`Secure`, `HttpOnly`, `SameSite=Strict`, 8 hours) and returns a CSRF token that
  every changing request (POST, PUT, PATCH, DELETE) must send back in the header `X-CSRF-Token`.
  Five wrong passwords lock the account for 15 minutes; a locked account and a wrong password both
  answer `401`.
- **Scanning PCs** enrol once with a one-time code (`POST /pcs/register`), receive an API key that is
  shown only then, and afterwards send `Authorization: Bearer <key>` to pull their configuration and
  report in.

Errors are JSON `{"detail": ...}`. Validation errors list only the field path, message and type,
never the value that was sent. The service has no interactive docs page (`/docs` is off).

"""


def build_app():
    from central.app import create_app
    from central.settings import Settings
    tmp = tempfile.mkdtemp(prefix="central_doc_")
    return create_app(Settings(database_url=f"sqlite:///{tmp}/doc.db", session_secret="x" * 40,
                               cookie_secure=False))


def _all_routes(app):
    """Every API route, however this FastAPI version stores included routers."""
    from central import (routes_admin_auth, routes_admin_config, routes_admin_fleet, routes_admin_overview,
                         routes_admin_pcs, routes_admin_users, routes_pcs)
    found = [r for r in app.routes if hasattr(r, "dependant")]
    for module in (routes_admin_auth, routes_admin_users, routes_admin_overview, routes_admin_fleet,
                   routes_admin_pcs, routes_admin_config, routes_pcs):
        found += [r for r in module.router.routes if hasattr(r, "dependant")]
    return [r for r in found if getattr(r, "include_in_schema", True)]


def _auth(route) -> str:
    names = [getattr(d.call, "__name__", "") for d in route.dependant.dependencies]
    found = [AUTH[n] for n in AUTH if n in names]
    if found:
        return " + ".join(found)
    return NO_AUTH.get(route.path, "none")


def _schema_summary(spec: dict, schema: dict | None) -> str:
    if not schema:
        return ""
    if "$ref" in schema:
        schema = spec["components"]["schemas"][schema["$ref"].rsplit("/", 1)[-1]]
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    rows = []
    for name, p in props.items():
        kind = p.get("type") or ("one of " + "/".join(
            str(x.get("type") or "object") for x in p.get("anyOf", []))) or "object"
        limits = ", ".join(f"{k} {p[k]}" for k in ("minLength", "maxLength", "minimum", "maximum") if k in p)
        rows.append(f"`{name}` ({kind}{', required' if name in required else ''}{'; ' + limits if limits else ''})")
    return "; ".join(rows)


def render() -> str:
    app = build_app()
    spec = app.openapi()
    routes = {}
    for route in _all_routes(app):
        for method in route.methods - {"HEAD", "OPTIONS"}:
            routes[(route.path, method.lower())] = route
    by_tag: dict[str, list] = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            tag = (op.get("tags") or ["other"])[0]
            by_tag.setdefault(tag, []).append((path, method, op, routes.get((path, method))))
    out = [HEADER]
    out.append("## Endpoints\n")
    out.append("| Method | Path | Who may call it |\n|---|---|---|")
    for tag in sorted(by_tag):
        for path, method, _op, route in sorted(by_tag[tag]):
            out.append(f"| {method.upper()} | `{path}` | {_auth(route) if route else '?'} |")
    out.append("")
    for tag in sorted(by_tag):
        out.append(f"## {tag}\n")
        for path, method, op, route in sorted(by_tag[tag]):
            out.append(f"### {method.upper()} `{path}`\n")
            doc = (getattr(getattr(route, "endpoint", None), "__doc__", None) or "").strip()
            if doc:
                out.append(doc + "\n")
            out.append(f"- **Who:** {_auth(route) if route else '?'}")
            params = [f"`{p['name']}` ({p['in']}{', required' if p.get('required') else ''})"
                      for p in op.get("parameters", [])]
            if params:
                out.append("- **Parameters:** " + "; ".join(params))
            body = (op.get("requestBody", {}).get("content", {}).get("application/json", {}) or {}).get("schema")
            summary = _schema_summary(spec, body)
            if summary:
                out.append("- **JSON body:** " + summary)
            codes = ", ".join(sorted(op.get("responses", {})))
            out.append(f"- **Replies:** {codes}\n")
    return "\n".join(out).rstrip() + "\n"


def main(argv=None) -> int:
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    text = render()
    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/CENTRAL_API.md is out of date: run python scripts/gen_api_doc.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT, f"({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
